"""Deterministic portable prompts and Codex skills; upstream stays untouched."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MARKER = "<!-- Generated by tools/ai/export-universal.py; edit source or generator. -->"
PRELUDE = """Read docs/ai/UNIVERSAL-PROTOCOL.md first. Its runtime adaptation rules
override vendor-specific mechanics and per-write prompts in the source below.
For game-production requests the default coordinator is docs/ai/STUDIO-DIRECTOR.md.
Next-step command suggestions are internal handoffs, never user typing requirements.
Resolve references/ beside this document; project paths are repository-relative.
Role/model/tool names are guidance, never grants or runtime configuration.
Use native delegation only when supported and authorized; otherwise do the
specialist passes sequentially and disclose that they are not independent.
"""

def split_frontmatter(text):
    match = re.match(r"\A---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
    return (match[1], text[match.end():].lstrip()) if match else ("", text)

def metadata(front):
    result = {}
    for line in front.splitlines():
        match = re.match(r"^([\w-]+):\s*(.*)$", line)
        if match:
            value = match[2]
            if value.startswith('"') and value.endswith('"'):
                value = json.loads(value)
            result[match[1]] = value
    return result

def transform(text, source):
    parts = source.parts
    if "skills" in parts:
        skill = parts[parts.index("skills")+1]
        text = text.replace("${CLAUDE_SKILL_DIR}", f".claude/skills/{skill}")
        if skill == "start" and source.name == "SKILL.md":
            text = text.replace("names the one next step. It never runs that step itself.",
                "selects the next step. The Codex studio director executes that step internally.")
            text = text.replace("template-remote note if it applies, and stop.",
                "template-remote note if it applies, then return to the director to resume the next unfinished step.")
            text = text.replace("Either answer leads to Phase 7, never to running the step.",
                "Use existing task authorization; a routine handoff needs no new permission. Continue via Phase 7.")
            text = text.replace('Ask: "Would you like to start with [first step]?" Options: `Yes, start with [first step]` /\n`Something else first`.',
                "Select the first needed step internally from the authorized objective. Do not ask the user to operate the handoff.")
            marker = "## Phase 7: Hand off"
            if marker not in text:
                raise ValueError("Upstream onboarding changed; inspect the director handoff adapter.")
            text = text.split(marker)[0] + """## Phase 7: Continue internally (Codex adaptation)

Record onboarding results and return to docs/ai/STUDIO-DIRECTOR.md. Read and
execute the selected workflow internally within the user's objective. The user
does not type a command. Onboarding complete is not the overall task complete.
Only unresolved material choices or missing capabilities stop this handoff.
"""
        if skill == "help" and source.name == "SKILL.md":
            text = text.replace("For each file, extract the `name:` field from its frontmatter.",
                "Read the matching name from ai/skills/index.json; adapted bodies have no frontmatter.")
    text = text.replace("${CLAUDE_PROJECT_DIR:-.}", ".").replace("${CLAUDE_PROJECT_DIR}", ".")
    text = re.sub(r"^!`(.*)`\s*$",
        lambda m: "Run this context command explicitly from the repository root "
        "(if shell access is available), and read its output before continuing:\n\n"
        "```bash\n" + m[1] + "\n```\n", text, flags=re.M)
    text = re.sub(r"\.claude/skills/[^/\s]+/\.\./\.\./(hooks|scripts)/", r".claude/\1/", text)
    for old, new in [(".claude/agents/", "ai/roles/"), (".claude/skills/", "ai/skills/"),
                     (".claude/docs/", "ai/docs/"), (".claude/rules/", "ai/rules/")]:
        text = text.replace(old, new)
    for old, new in {"AskUserQuestion": "ask_user", "TaskCreate": "task_create",
                     "TaskGet": "task_read", "TaskList": "task_list",
                     "TaskUpdate": "task_update", "TeamCreate": "team_create",
                     "TeamDelete": "team_close"}.items():
        text = re.sub(r"\b" + old + r"\b", new, text)
    text = text.replace("$ARGUMENTS", "TASK_ARGUMENTS")
    return re.sub(r"^@(\S+)$", r"Read \1 when relevant.", text, flags=re.M)

def collect(root=ROOT):
    outputs, roles, skills, rules = {}, [], [], []
    src = root / ".claude"
    for category, target in (("agents", "roles"), ("skills", "skills"),
                             ("docs", "docs"), ("rules", "rules")):
        for path in sorted((src / category).rglob("*"), key=lambda p: p.relative_to(root).as_posix()):
            if not path.is_file():
                continue
            rel = path.relative_to(src / category)
            destination = Path("ai") / target / rel
            if path.suffix != ".md":
                outputs[destination.as_posix()] = path.read_bytes()
                continue
            front, body = split_frontmatter(path.read_text(encoding="utf-8"))
            meta = metadata(front)
            source_name = path.relative_to(root).as_posix()
            if category == "agents":
                roles.append({"name": path.stem, "description": meta.get("description", ""),
                              "path": destination.as_posix(), "source": source_name,
                              "source_metadata": meta})
            if category == "rules":
                rules.append({"name": path.stem, "path": destination.as_posix(), "source_scope": front})
            if category == "skills" and path.name == "SKILL.md":
                name = rel.parts[0]
                skills.append({"name": name, "description": meta.get("description", ""),
                               "path": destination.as_posix(), "source": source_name})
                wrapper = Path(".agents/skills") / ("studio-" + name) / "SKILL.md"
                outputs[wrapper.as_posix()] = (
                    "---\nname: studio-" + name + "\ndescription: " +
                    json.dumps("Game Studios: " + meta.get("description", name), ensure_ascii=False) +
                    "\n---\n\n" + MARKER + "\n\n"
                    "Use this workflow in a Game Studios project. Locate the repository root "
                    "containing AGENTS.md and project.yaml.\n\n"
                    "1. Read docs/ai/UNIVERSAL-PROTOCOL.md and docs/ai/STUDIO-DIRECTOR.md.\n"
                    f"2. Read {destination.as_posix()} and follow its referenced phases on demand.\n"
                    "3. Treat the user's task text as TASK_ARGUMENTS; do not execute slash commands "
                    "as shell commands. Use the host's current model and tools.\n"
                    "4. Apply relevant rules listed in ai/rules/index.json before editing files.\n"
                    "5. Return results to the director and continue the next authorized step; "
                    "do not tell the user to type the next skill command.\n"
                ).encode()
            scope = ("\n## Original path scope (apply manually)\n\n```yaml\n" + front +
                     "\n```\n") if category == "rules" and front else ""
            outputs[destination.as_posix()] = (
                MARKER + "\n\n> Adapted from `" + source_name + "`; upstream MIT license applies.\n\n" +
                PRELUDE + scope + "\n" + transform(body, path)).encode()
    for target, entries in (("roles", roles), ("skills", skills), ("rules", rules)):
        outputs[f"ai/{target}/index.json"] = (json.dumps(entries, indent=2, ensure_ascii=False)+"\n").encode()
    outputs["ai/README.md"] = (MARKER + """
# Portable Game Studios
Use roles/index.json, skills/index.json and rules/index.json to locate content.
Codex discovers wrappers in .agents/skills/studio-*/SKILL.md.
Other assistants read AGENTS.md and these same Markdown files directly.

Generated copies are not edit targets. Edit .claude/ content or the converter,
then run python tools/ai/export-universal.py. Use --check to detect drift.
Shared Bash helpers still live under .claude/scripts and .claude/hooks;
their existence does not install Claude event hooks on other hosts.
""").encode()
    outputs["ai/docs/config-resolution.md"] = (MARKER + """
# Portable config resolution
Read docs/ai/UNIVERSAL-PROTOCOL.md. There is no injected shell execution here.
From the repository root, when Bash and Python 3 are available:
```bash
bash .claude/hooks/yaml-helper.sh resolve_config
```
This reuses the upstream resolver: local YAML, project YAML, legacy settings,
rigor expansion and defaults. Verify Python is a real interpreter before trusting
output; upstream can silently fall back without Python. Without tools, consult
.claude/docs/config-resolution.md as a reference and read actual configuration;
disclose unresolved values. "Resolved above" never means the command already ran.
Host permissions and the user's existing authorization always take precedence.
""").encode()
    manifest = {
        "format": 1,
        "upstream": "https://github.com/Donchitos/Claude-Code-Game-Studios",
        "source_sha256": {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                          for category in ("agents", "skills", "docs", "rules", "scripts", "hooks")
                          for p in sorted((src/category).rglob("*"), key=lambda p: p.relative_to(root).as_posix())
                          if p.is_file() and p.suffix != ".pyc"},
        "generated_sha256": {p: hashlib.sha256(b).hexdigest() for p,b in sorted(outputs.items())},
        "counts": {"roles": len(roles), "skills": len(skills), "rules": len(rules)},
    }
    outputs["ai/manifest.json"] = (json.dumps(manifest, indent=2)+"\n").encode()
    return outputs

def run(check=False, root=ROOT):
    outputs = collect(root)
    previous_file = root / "ai/manifest.json"
    previous = json.loads(previous_file.read_text()) if previous_file.exists() else {}
    old_hashes = previous.get("generated_sha256", {})
    drift = []
    # Preflight everything before updating, so local edits don't cause partial export.
    for name, digest in old_hashes.items():
        path = (root / name).resolve()
        if not path.is_relative_to(root.resolve()) or name.split("/")[0] not in ("ai", ".agents"):
            raise ValueError(f"Unsafe manifest path: {name}")
        if path.exists() and hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Generated file edited locally: {name}. Move edits to source first.")
    for name, data in outputs.items():
        path = root / name
        if path.exists() and path.read_bytes() == data:
            continue
        if check:
            drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for name in old_hashes:
        path = root / name
        if name not in outputs and path.exists():
            if check:
                drift.append(name)
            else:
                path.unlink()
    if drift:
        raise ValueError("Generated layer out of date: " + ", ".join(drift[:8]))
    return len(outputs)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        print(f"{'Checked' if args.check else 'Generated'} {run(args.check)} files.")
    except ValueError as exc:
        parser.exit(1, str(exc)+"\n")
